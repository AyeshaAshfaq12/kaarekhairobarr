import 'server-only'
import React from 'react'
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from '@react-pdf/renderer'
import { formatDate, formatDateTime, formatPKR } from './time'

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 10, fontFamily: 'Helvetica', color: '#0f1917' },
  title: { fontSize: 16, fontFamily: 'Helvetica-Bold', marginBottom: 4 },
  section: { fontSize: 12, fontFamily: 'Helvetica-Bold', marginTop: 16, marginBottom: 6 },
  row: { flexDirection: 'row', paddingVertical: 2 },
  label: { width: 150, color: '#54706b' },
  cell: { flex: 1 },
  footer: { position: 'absolute', bottom: 24, left: 40, right: 40, fontSize: 8, color: '#768f8a' },
})

export type MyData = {
  generatedFor: string
  profile: { label: string; value: string }[]
  signatures: { version: number; signedAt: Date; typedName: string; bodySha256: string }[]
  donations: { receivedAt: Date; donor: string; caseTitle: string; amount: number; status: string }[]
}

// "A member can download their own data (profile, NDA copy, their donations) as a PDF" (§11.4).
export async function renderMyDataPdf(data: MyData) {
  const generatedAt = new Date()
  return renderToBuffer(
    <Document title={`KKB — data for ${data.generatedFor}`}>
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>Kaare Khair o Barr — my data</Text>
        <Text>{data.generatedFor}</Text>

        <Text style={styles.section}>Profile</Text>
        {data.profile.map((item) => (
          <View key={item.label} style={styles.row}>
            <Text style={styles.label}>{item.label}</Text>
            <Text style={styles.cell}>{item.value || '—'}</Text>
          </View>
        ))}

        <Text style={styles.section}>Signed agreements</Text>
        {data.signatures.map((signature) => (
          <View key={signature.version} style={styles.row}>
            <Text style={styles.label}>Version {signature.version}</Text>
            <Text style={styles.cell}>
              Signed {formatDateTime(signature.signedAt)} as &quot;{signature.typedName}&quot; · SHA-256 {signature.bodySha256.slice(0, 16)}…
            </Text>
          </View>
        ))}

        <Text style={styles.section}>Donations credited to me</Text>
        {data.donations.length === 0 ? <Text>None.</Text> : null}
        {data.donations.map((donation, index) => (
          <View key={index} style={styles.row} wrap={false}>
            <Text style={{ width: 80 }}>{formatDate(donation.receivedAt)}</Text>
            <Text style={styles.cell}>
              {donation.donor} → {donation.caseTitle}
            </Text>
            <Text style={{ width: 90, textAlign: 'right' }}>{formatPKR(donation.amount)}</Text>
            <Text style={{ width: 70, textAlign: 'right' }}>{donation.status.toLowerCase()}</Text>
          </View>
        ))}

        <Text style={styles.footer} fixed>
          Generated by {data.generatedFor} on {formatDateTime(generatedAt)} (Asia/Karachi). CNIC is never included in exports.
        </Text>
      </Page>
    </Document>
  )
}
