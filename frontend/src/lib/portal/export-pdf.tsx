import 'server-only'
import React from 'react'
import { readFileSync } from 'fs'
import path from 'path'
import { Document, Image, Page, StyleSheet, Text, View, renderToBuffer } from '@react-pdf/renderer'
import { formatCell, type Report } from './reports'
import { formatDateTime } from './time'

const styles = StyleSheet.create({
  page: { paddingTop: 36, paddingBottom: 48, paddingHorizontal: 32, fontSize: 8, fontFamily: 'Helvetica', color: '#0f1917' },
  header: { flexDirection: 'row', alignItems: 'center', marginBottom: 14 },
  logo: { width: 36, height: 36, marginRight: 10 },
  title: { fontSize: 14, fontFamily: 'Helvetica-Bold' },
  meta: { fontSize: 8, color: '#54706b', marginTop: 2 },
  tableTitle: { fontSize: 10, fontFamily: 'Helvetica-Bold', marginTop: 12, marginBottom: 4 },
  row: { flexDirection: 'row', borderBottomWidth: 0.5, borderColor: '#cdd9d7', paddingVertical: 3 },
  headRow: { flexDirection: 'row', backgroundColor: '#f7efe2', paddingVertical: 4 },
  cell: { flex: 1, paddingHorizontal: 3 },
  num: { flex: 1, paddingHorizontal: 3, textAlign: 'right' },
  bold: { fontFamily: 'Helvetica-Bold' },
  note: { marginTop: 8, color: '#39524e' },
  footer: { position: 'absolute', bottom: 20, left: 32, right: 32, fontSize: 7, color: '#768f8a', flexDirection: 'row', justifyContent: 'space-between' },
})

function logo() {
  try {
    return readFileSync(path.join(process.cwd(), 'public', 'kaare-khair-logo.png'))
  } catch {
    return null
  }
}

/** PDF export (§10.3): KKB logo, title, scope, period; generated-by and timestamp in the footer. */
export async function reportToPdf(report: Report, generatedBy: string) {
  const image = logo()
  const wide = report.tables.some((table) => table.columns.length > 7)
  const generatedAt = formatDateTime(new Date())
  return renderToBuffer(
    <Document title={`${report.title} — ${report.period}`}>
      <Page size="A4" orientation={wide ? 'landscape' : 'portrait'} style={styles.page}>
        <View style={styles.header} fixed>
          {/* eslint-disable-next-line jsx-a11y/alt-text */}
          {image ? <Image src={image} style={styles.logo} /> : null}
          <View>
            <Text style={styles.title}>{report.title}</Text>
            <Text style={styles.meta}>
              Kaare Khair o Barr · {report.scopeLabel} · {report.period}
            </Text>
          </View>
        </View>
        {report.tables.map((table) => (
          <View key={table.name}>
            <Text style={styles.tableTitle}>{table.name}</Text>
            <View style={styles.headRow} fixed>
              {table.columns.map((column) => (
                <Text key={column.key} style={[column.kind && column.kind !== 'text' ? styles.num : styles.cell, styles.bold]}>
                  {column.label}
                </Text>
              ))}
            </View>
            {table.rows.length === 0 ? <Text style={styles.note}>No rows.</Text> : null}
            {table.rows.map((row, index) => (
              <View key={index} style={styles.row} wrap={false}>
                {table.columns.map((column) => (
                  <Text key={column.key} style={column.kind && column.kind !== 'text' ? styles.num : styles.cell}>
                    {formatCell(row[column.key], column.kind)}
                  </Text>
                ))}
              </View>
            ))}
          </View>
        ))}
        {(report.notes ?? []).map((note) => (
          <Text key={note} style={styles.note}>
            {note}
          </Text>
        ))}
        <View style={styles.footer} fixed>
          <Text>
            Generated by {generatedBy} · {generatedAt} (Asia/Karachi) · CNICs are never exported
          </Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
        </View>
      </Page>
    </Document>
  )
}
