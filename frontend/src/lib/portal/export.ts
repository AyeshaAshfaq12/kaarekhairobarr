import 'server-only'
import ExcelJS from 'exceljs'
import type { Report } from './reports'
import { formatDateTime } from './time'

const PKR_FORMAT = '"PKR" #,##0;[Red]-"PKR" #,##0'

/** Excel export (§10.3): one sheet per table, PKR formatting, frozen header. */
export async function reportToXlsx(report: Report, generatedBy: string) {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = 'KKB Portal'
  workbook.created = new Date()
  const used = new Set<string>()
  for (const table of report.tables) {
    // Sheet names: max 31 chars, unique, no []:*?/\
    let name = table.name.replace(/[[\]:*?/\\]/g, ' ').slice(0, 31) || 'Sheet'
    for (let i = 2; used.has(name); i += 1) name = `${table.name.slice(0, 28)} ${i}`
    used.add(name)
    const sheet = workbook.addWorksheet(name, { views: [{ state: 'frozen', ySplit: 1 }] })
    sheet.columns = table.columns.map((column) => ({
      header: column.label,
      key: column.key,
      width: Math.min(48, Math.max(12, column.label.length + 4, ...table.rows.slice(0, 200).map((row) => String(row[column.key] ?? '').length + 2))),
      style: column.kind === 'pkr' ? { numFmt: PKR_FORMAT } : column.kind === 'percent' ? { numFmt: '0%' } : column.kind === 'number' ? { numFmt: '#,##0.##' } : {},
    }))
    sheet.getRow(1).font = { bold: true }
    sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF7EFE2' } }
    for (const row of table.rows) sheet.addRow(row)
  }
  const info = workbook.addWorksheet('About')
  info.addRows([
    ['Report', report.title],
    ['Scope', report.scopeLabel],
    ['Period', report.period],
    ['Generated by', generatedBy],
    ['Generated at', `${formatDateTime(new Date())} (Asia/Karachi)`],
    ...(report.notes ?? []).map((note) => ['Note', note]),
  ])
  info.getColumn(1).font = { bold: true }
  info.getColumn(1).width = 16
  info.getColumn(2).width = 60
  return Buffer.from(await workbook.xlsx.writeBuffer())
}
